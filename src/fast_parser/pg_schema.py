"""PostgreSQL 16 layout: monthly partitions, Russian FTS, lz4 text, trgm.

SQLite keeps the same ORM tables without partitions. Dedup stays in the
application, because a partitioned unique key must include published_at.
"""

from __future__ import annotations

from datetime import date

from sqlalchemy import text
from sqlalchemy.engine import Engine

_ARTICLE_COLUMNS = """
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_id VARCHAR(64) NOT NULL,
    source_nid INTEGER,
    region_id SMALLINT,
    district_id SMALLINT,
    category_id SMALLINT,
    feed_id INTEGER,
    guid VARCHAR(1024),
    url VARCHAR(2048) NOT NULL,
    canonical_url VARCHAR(2048) NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    title TEXT NOT NULL DEFAULT '',
    summary TEXT,
    text TEXT NOT NULL DEFAULT '',
    authors JSON,
    language VARCHAR(16),
    published_at TIMESTAMP,
    fetched_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    category VARCHAR(128),
    category_confidence DOUBLE PRECISION,
    sentiment VARCHAR(16),
    sentiment_score DOUBLE PRECISION,
    fake_score DOUBLE PRECISION,
    fake_label VARCHAR(64),
    content_origin VARCHAR(32) NOT NULL DEFAULT 'rss',
    pipeline_status VARCHAR(32) NOT NULL DEFAULT 'pending',
    domain VARCHAR(255),
    text_length INTEGER,
    tags JSON,
    extra JSON,
    embedding BYTEA,
    search_vector tsvector,
    PRIMARY KEY (id, published_at)
"""


def ensure_postgres(engine: Engine) -> None:
    with engine.begin() as conn:
        conn.execute(text("CREATE EXTENSION IF NOT EXISTS pg_trgm"))
        _ensure_lookup_tables(conn)
        if not _articles_partitioned(conn):
            conn.execute(text(f"CREATE TABLE articles ({_ARTICLE_COLUMNS}) PARTITION BY RANGE (published_at)"))
            conn.execute(text("CREATE TABLE articles_default PARTITION OF articles DEFAULT"))
            _search_trigger(conn)
        ensure_month_range(conn, date(2020, 1, 1), date(2028, 1, 1))
        _ensure_article_columns(conn)
        _indexes(conn)
        _compress(conn)


def ensure_month_range(conn, start: date, end: date) -> None:
    year, month = start.year, start.month
    while (year, month) < (end.year, end.month):
        nxt_year, nxt_month = (year + 1, 1) if month == 12 else (year, month + 1)
        name = f"articles_{year}_{month:02d}"
        conn.execute(
            text(
                f"""
                CREATE TABLE IF NOT EXISTS {name} PARTITION OF articles
                FOR VALUES FROM ('{year}-{month:02d}-01') TO ('{nxt_year}-{nxt_month:02d}-01')
                """
            )
        )
        year, month = nxt_year, nxt_month


def _articles_partitioned(conn) -> bool:
    row = conn.execute(
        text(
            """
            SELECT c.relkind = 'p'
            FROM pg_class c
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = 'public' AND c.relname = 'articles'
            """
        )
    ).scalar()
    return bool(row)


def _ensure_lookup_tables(conn) -> None:
    conn.execute(
        text(
            """
            CREATE TABLE IF NOT EXISTS federal_districts (
                id SMALLINT PRIMARY KEY,
                name VARCHAR(64) UNIQUE NOT NULL
            )
            """
        )
    )
    conn.execute(
        text(
            """
            CREATE TABLE IF NOT EXISTS regions (
                id SMALLINT PRIMARY KEY,
                code VARCHAR(8) UNIQUE NOT NULL,
                name VARCHAR(128) NOT NULL,
                district_id SMALLINT REFERENCES federal_districts (id)
            )
            """
        )
    )
    conn.execute(
        text(
            """
            CREATE TABLE IF NOT EXISTS categories (
                id SMALLINT PRIMARY KEY,
                title VARCHAR(128) UNIQUE NOT NULL
            )
            """
        )
    )
    conn.execute(
        text(
            """
            CREATE TABLE IF NOT EXISTS saved_searches (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(128) UNIQUE NOT NULL,
                query_json JSON NOT NULL,
                created_at TIMESTAMP NOT NULL
            )
            """
        )
    )
    # sources/feeds/logs come from the ORM so the collector can share them.
    from fast_parser.models import Base

    Base.metadata.create_all(
        conn,
        tables=[
            table
            for table in Base.metadata.sorted_tables
            if table.name in {"sources", "feeds", "feed_states", "fetch_logs"}
        ],
    )


def _search_trigger(conn) -> None:
    conn.execute(
        text(
            """
            CREATE OR REPLACE FUNCTION articles_search_vector_update() RETURNS trigger AS $$
            BEGIN
                NEW.search_vector :=
                    setweight(to_tsvector('russian', coalesce(NEW.title, '')), 'A') ||
                    setweight(to_tsvector('russian', coalesce(NEW.text, '')), 'B');
                RETURN NEW;
            END
            $$ LANGUAGE plpgsql
            """
        )
    )
    conn.execute(
        text(
            """
            CREATE TRIGGER articles_search_vector_trg
            BEFORE INSERT OR UPDATE OF title, text ON articles
            FOR EACH ROW EXECUTE FUNCTION articles_search_vector_update()
            """
        )
    )


def _ensure_article_columns(conn) -> None:
    present = {
        row[0]
        for row in conn.execute(
            text(
                """
                SELECT column_name FROM information_schema.columns
                WHERE table_schema = 'public' AND table_name = 'articles'
                """
            )
        )
    }
    wanted = {
        "category_confidence": "DOUBLE PRECISION",
        "fake_label": "VARCHAR(64)",
        "domain": "VARCHAR(255)",
        "text_length": "INTEGER",
        "tags": "JSON",
    }
    for name, ddl in wanted.items():
        if name not in present:
            conn.execute(text(f"ALTER TABLE articles ADD COLUMN {name} {ddl}"))


def _indexes(conn) -> None:
    statements = [
        "CREATE INDEX IF NOT EXISTS ix_articles_published_at ON articles (published_at)",
        "CREATE INDEX IF NOT EXISTS ix_articles_source_id ON articles (source_id)",
        "CREATE INDEX IF NOT EXISTS ix_articles_source_nid ON articles (source_nid)",
        "CREATE INDEX IF NOT EXISTS ix_articles_region_id ON articles (region_id)",
        "CREATE INDEX IF NOT EXISTS ix_articles_district_id ON articles (district_id)",
        "CREATE INDEX IF NOT EXISTS ix_articles_category_id ON articles (category_id)",
        "CREATE INDEX IF NOT EXISTS ix_articles_sentiment ON articles (sentiment)",
        "CREATE INDEX IF NOT EXISTS ix_articles_language ON articles (language)",
        "CREATE INDEX IF NOT EXISTS ix_articles_domain ON articles (domain)",
        "CREATE INDEX IF NOT EXISTS ix_articles_pipeline ON articles (pipeline_status)",
        "CREATE INDEX IF NOT EXISTS ix_articles_fetched_at ON articles (fetched_at)",
        "CREATE INDEX IF NOT EXISTS ix_articles_content_hash ON articles (source_id, content_hash)",
        "CREATE INDEX IF NOT EXISTS ix_articles_canonical_url ON articles (canonical_url)",
        "CREATE INDEX IF NOT EXISTS ix_articles_search ON articles USING GIN (search_vector)",
        "CREATE INDEX IF NOT EXISTS ix_articles_title_trgm ON articles USING GIN (title gin_trgm_ops)",
    ]
    for statement in statements:
        conn.execute(text(statement))


def _compress(conn) -> None:
    rows = conn.execute(
        text(
            """
            SELECT inhrelid::regclass::text
            FROM pg_inherits
            WHERE inhparent = 'articles'::regclass
            """
        )
    ).all()
    targets = ["articles", *[row[0] for row in rows]]
    for table in targets:
        for column in ("title", "summary", "text"):
            conn.execute(text(f"ALTER TABLE {table} ALTER COLUMN {column} SET COMPRESSION lz4"))
